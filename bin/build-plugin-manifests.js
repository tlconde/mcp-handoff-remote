#!/usr/bin/env node
'use strict';
/**
 * GENERATE the Claude Code manifests FROM the portable ones. One writer, never two authors.
 *
 * WHY THIS EXISTS RATHER THAN TWO HAND-KEPT FILES. This repo already carries the scar: the tool
 * list lived in two places, the remote surface quietly diverged from the local one, and
 * handoff-tool-schemas.js was created to end it — "Two hand-maintained copies of a tool list is how
 * a remote surface quietly drifts from the local one." Packaging is the same shape one layer up,
 * on the artifact a stranger meets first. So plugin.json + mcp.json (the agent-plugins.org
 * standard) are the SOURCE, and .claude-plugin/* is OUTPUT.
 *
 * WHY THE STANDARD IS THE SOURCE AND NOT THE CLIENT FORMAT. Portability is the product thesis, not
 * decoration — handing a session between different harnesses is the point, so the format that
 * belongs to no vendor is the one that gets to be true. A client-specific manifest generated from a
 * portable one stays portable by construction; the reverse arrangement decays the moment a second
 * client matters.
 *
 * WHAT DIFFERS BETWEEN THEM, and therefore what this file translates:
 *   manifest location   plugin.json (root)        ->  .claude-plugin/plugin.json
 *   MCP config          mcp.json (root)           ->  inlined as `mcpServers`
 *   path placeholder    ${PLUGIN_ROOT}            ->  ${CLAUDE_PLUGIN_ROOT}
 *   hooks / monitors    extensions[<client key>]  ->  hooks/hooks.json and `experimental.monitors`
 *   marketplace         (not in the standard)     ->  .claude-plugin/marketplace.json
 *
 * The marketplace is generated too, and self-hosts: this repo is its own marketplace, so install is
 * two commands against a repo that exists rather than a publication step first.
 *
 *   node bin/build-plugin-manifests.js            write the generated files
 *   node bin/build-plugin-manifests.js --check    write nothing; exit 1 if anything is stale
 *
 * --check is what the suite runs. A generated file edited by hand fails it, which is the whole
 * point: the only way to change the output is to change the source.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CLIENT_KEY = 'com.anthropic.claude-code';
const CHECK = process.argv.includes('--check');

const read = f => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

/* ${PLUGIN_ROOT} is the standard's placeholder; Claude Code expands ${CLAUDE_PLUGIN_ROOT}. Rewritten
 * rather than duplicated, so a path is written once in the portable file and translated on the way
 * out. Deep, because it appears in args, env and cwd. */
function toClaudePlaceholders(v) {
  if (typeof v === 'string') return v.replace(/\$\{PLUGIN_ROOT\}/g, '${CLAUDE_PLUGIN_ROOT}')
    .replace(/\$\{PLUGIN_DATA\}/g, '${CLAUDE_PLUGIN_DATA}');
  if (Array.isArray(v)) return v.map(toClaudePlaceholders);
  if (v && typeof v === 'object') {
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, toClaudePlaceholders(x)]));
  }
  return v;
}

const GENERATED_NOTE = 'GENERATED by bin/build-plugin-manifests.js from plugin.json + mcp.json. Do not edit: `node bin/build-plugin-manifests.js --check` fails on hand edits. Change the source and regenerate.';

function build() {
  const src = read('plugin.json');
  const mcp = read('mcp.json');
  const ext = (src.extensions && src.extensions[CLIENT_KEY]) || {};

  /* The standard's mcp.json carries a `type` per server; Claude Code infers stdio from `command`
   * and does not document a `type` field, so it is dropped rather than passed through. Carrying a
   * field a client does not read is how a manifest starts lying about what it configures. */
  const mcpServers = Object.fromEntries(Object.entries(mcp.mcpServers || {}).map(([name, cfg]) => {
    const { type, ...rest } = cfg;
    return [name, toClaudePlaceholders(rest)];
  }));

  const pluginManifest = {
    _generated: GENERATED_NOTE,
    name: src.name,
    version: src.version,
    description: src.description,
    author: src.author,
    license: src.license,
    keywords: src.keywords,
    mcpServers,
  };
  /* Optional-and-absent stays absent rather than emitting `undefined`: a manifest with null fields
   * claims to describe something it does not. Added back automatically once the source carries
   * them, which is the only place they should ever be typed. */
  if (src.homepage) pluginManifest.homepage = src.homepage;
  if (src.repository) pluginManifest.repository = src.repository;
  if (ext.monitors) pluginManifest.experimental = { monitors: toClaudePlaceholders(ext.monitors) };

  const hooks = ext.hooks ? { _generated: GENERATED_NOTE, hooks: toClaudePlaceholders(ext.hooks) } : null;

  /* SELF-HOSTED MARKETPLACE: source "./" — this repo IS the plugin, so the marketplace entry points
   * at its own root. Nothing has to be published anywhere before the two-command install works. */
  const marketplace = {
    _generated: GENERATED_NOTE,
    name: src.name,
    owner: { name: (src.author && src.author.name) || src.name },
    plugins: [{
      name: src.name,
      source: './',
      description: src.description,
      version: src.version,
      license: src.license,
      keywords: src.keywords,
      ...(src.homepage ? { homepage: src.homepage } : {}),
      ...(src.repository ? { repository: src.repository } : {}),
    }],
  };

  return {
    '.claude-plugin/plugin.json': pluginManifest,
    '.claude-plugin/marketplace.json': marketplace,
    ...(hooks ? { 'hooks/hooks.json': hooks } : {}),
  };
}

function main() {
  const outputs = build();
  const stale = [];
  for (const [rel, obj] of Object.entries(outputs)) {
    const abs = path.join(ROOT, rel);
    const next = JSON.stringify(obj, null, 2) + '\n';
    let current = null;
    try { current = fs.readFileSync(abs, 'utf8'); } catch (_) {}
    if (current === next) continue;
    if (CHECK) { stale.push(rel + (current === null ? ' (missing)' : ' (differs from source)')); continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, next);
    console.log(`wrote ${rel}`);
  }
  if (CHECK) {
    if (stale.length) {
      console.error('STALE generated manifests:\n  ' + stale.join('\n  '));
      console.error('\nThese are OUTPUT, not source. Edit plugin.json / mcp.json and run:\n  node bin/build-plugin-manifests.js');
      process.exit(1);
    }
    console.log('generated manifests match their source');
  }
}

if (require.main === module) main();
module.exports = { build, toClaudePlaceholders, CLIENT_KEY };
